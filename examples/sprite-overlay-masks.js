module.exports = ({ KIT:K, makeBuilder }) => ({
  id:'sprite-overlay-masks', name:'The Crimson Lock', seed:23,
  build(seed) {
    function card(strokes, z, transitions, objectId) {
      const metadata = {width:W,height:H,emissionMode:'baked',frames:[{rect:{x:0,y:0,width:W,height:H}}],
        ...(transitions && {cels:{transitions}})};
      const atlas = K.sprite.atlas({metadata,images:{color:K.pixelStamps.image({width:W,height:H,palette:colors,strokes}).rgba}});
      return K.sprite.placeAtlas({atlas,objectId,at:[0,0,z],mode:'card',nativePixels:true,lighting:false});
    }
    const swatches = [...colors,...eyePalette].map(color=>parseInt(color.slice(1),16));
    return makeBuilder(seed,swatches).finish({
      cam:{target:[0,0,0],dist:6,yaw:0,pitch:0,ortho:true,sway:0},radius:8,dither:0,
      spriteAtlases:[card(background(K,seed),-1),card(actor(),.25,layers(),'crimson-lock')],
      look:{effects:{glow:{radius:2,threshold:.26,colors:['#663044','#a34551']}}}
    });
  }
});
