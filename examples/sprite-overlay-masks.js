function patch(box, strokes) {
  const [x,y] = box;
  return { strokes:strokes.map(({slot,shape})=>({slot,
    shape:shape.rect ? {...shape,rect:[shape.rect[0]-x,shape.rect[1]-y,shape.rect[2],shape.rect[3]]} :
      {...shape,points:shape.points.map(([u,v])=>[u-x,v-y])}
  })) };
}

