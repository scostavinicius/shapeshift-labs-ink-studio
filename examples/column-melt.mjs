function controlPaint() {
  const data = new Uint8Array(strips * 3 * 4);
  for (let i = 3; i < data.length; i += 4) data[i] = 255;
  const strip = (x, channel, value) => { data[(channel * strips + x) * 4 + channel] = value; };
  for (const [x, value] of [[10,149],[11,214],[12,255],[13,224],[14,150],[43,168],[44,237],[45,179]]) {
    strip(x, 0, value);
  }
  for (let x = 25; x <= 31; x++) strip(x, 1, [134,199,248,255,247,194,132][x-25]);
  for (const [x, value] of [[7,115],[8,209],[9,255],[10,255],[11,248],[12,138],
    [34,144],[35,239],[36,255],[37,247],[38,135],[52,161],[53,227],[54,178]]) {
    strip(x, 2, value);
  }
  return { width: strips, height: 3, data };
}

const from = overlook(), to = undercroft(), paint = controlPaint();
const map = createColumnMeltMap(paint, { strips, spread });
const out = process.argv[2] ?? 'out/column-melt';
mkdirSync(out, { recursive: true });
const fps = 24, count = 65;
const frames = Array.from({ length: count }, (_, index) => png.packRGBA(
  renderColumnMelt(from, to, { map, progress: (index - 11) / 40 })
));
writeFileSync(join(out, 'lantern-sluice.png'), png.encodeAnimation(frames, fps));
for (const [name, image] of [['overlook', from], ['undercroft', to],
  ['melt-front', renderColumnMelt(from, to, { map, progress: 0.73 })]]) {
  writeFileSync(join(out, name + '.png'), png.encodeFrame(png.packRGBA(image)));
}

