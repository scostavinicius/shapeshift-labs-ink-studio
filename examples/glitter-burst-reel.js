function fleck(palette) {
  return {width:5,height:3,palette,frames:[
    {duration:.10,rows:['.....','.5...','.....']},
    {duration:.09,rows:['..3..','.46..','.....']},
    {duration:.10,rows:['...4.','..53.','.....']},
    {duration:.13,rows:['....3','..3..','.....']},
    {duration:.18,rows:['....2','.....','.....']},
    {duration:.90}
  ]};
}

module.exports=({KIT:K,makeBuilder})=>({
  id:'glitter-burst-reel',name:'Glitter Burst Reel',seed:19,
  build(seed) {
    const fork=K.pixelStamps.clip('burst-fork'),diamond=K.pixelStamps.clip('burst-diamond'),fan=K.pixelStamps.clip('burst-fan');
    const dust=fleck(fork.palette);
    const b=makeBuilder(seed,[...tones,...fork.palette].map(c=>parseInt(c.slice(1),16)));
    const cards=[{stamp:backdrop(),at:at(W/2,H/2,-2),unitsPerPixel:U}];
    const place=(stamp,x,y,phase)=>cards.push({stamp,at:at(x,y,0),phase,nativePixels:true});
    place(fork,42.5,25.5,.01);
    place(diamond,121.5,25.5,.01);
    place(fan,201.5,25.5,.01);
    for(const [stamp,x,y,phase] of [[fan,66.5,88.5,-.12],[fork,111.5,72.5,-.44],[diamond,159.5,78.5,-.72],
      [fan,205.5,64.5,-.99]]) place(stamp,x,y,phase);
    for(const [x,y,phase] of [[40.5,93.5,-.01],[46.5,90.5,-.09],[55.5,92.5,-.22],[61.5,84.5,-.24],
      [77.5,82.5,-.33],[84.5,84.5,-.37],[88.5,88.5,-.40],[95.5,77.5,-.42],[104.5,67.5,-.48],
      [118.5,81.5,-.55],[125.5,70.5,-.56],[132.5,75.5,-.62],[140.5,80.5,-.66],[146.5,71.5,-.70],
      [152.5,84.5,-.74],[167.5,71.5,-.79],[175.5,82.5,-.85],[183.5,72.5,-.88],[189.5,70.5,-.94],
      [211.5,76.5,-1.08],[218.5,67.5,-1.14],[227.5,60.5,-1.19],[230.5,69.5,-1.21]]) place(dust,x,y,phase);
    return b.finish({cam:{target:at(W/2,H/2,0),dist:D,pitch:0,yaw:0,sway:0,projection:'orthographic',fov:2*Math.atan(H*U/(2*D))},
      pixelStamps:cards,dither:0,radius:16,detail:23});
  }
});
